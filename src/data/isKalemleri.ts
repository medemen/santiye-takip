export const IS_KALEMLERI: readonly string[] = IMALAT_GRUPLARI.flatMap(
  (g) => g.kalemler
);

export function getGrupById(grupId: string): ImalatGrubu | undefined {
  return IMALAT_GRUPLARI.find((g) => g.id === grupId);
}

export function getGrupByKalem(kalem: string): ImalatGrubu | undefined {
  return IMALAT_GRUPLARI.find((g) => g.kalemler.includes(kalem));
}

